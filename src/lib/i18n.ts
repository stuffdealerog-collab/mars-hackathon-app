export type MessageKey = keyof (typeof dictionaries)["en"];

/** All texts per locale (read-only; for key-parity tests and tooling). */
export const DICTIONARIES: Readonly<Record<Locale, Readonly<Record<string, string>>>> = dictionaries;

/** Maps a Telegram `language_code` (IETF tag) to a supported locale. Default: uz. */
export function pickLocale(code?: string | null): Locale {
  const base = (code ?? "").toLowerCase().split(/[-_]/)[0];
  if (base === "uz") return "uz";
  if (base === "en") return "en";
  if (["ru", "uk", "be", "kk", "ky", "tg"].includes(base)) return "ru";
  return DEFAULT_LOCALE;
}

/** The bot's handle when a caller passes none (servers pass "@" + BOT_USERNAME). */
export const DEFAULT_BOT_HANDLE = "@mercatai";

export function t(
  locale: Locale,
  key: MessageKey,
  vars: Record<string, string | number> = {},
): string {
  const template: string = dictionaries[locale]?.[key] ?? dictionaries[DEFAULT_LOCALE][key];
  const all: Record<string, string | number> = { bot: DEFAULT_BOT_HANDLE, ...vars };
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in all ? String(all[name]) : match,
  );
}

